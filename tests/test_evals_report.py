"""Gate on the committed live-evals report.

CI has no AWS credentials, so it cannot run the live evals itself; what it
CAN hold is the recorded run: evals/results/latest.json is generated by
`uv run python -m evals.run_evals` against real Nova and committed. This
gate fails (never skips) if the report is missing, malformed, stale in
shape, or recorded anything less than a passing run, so the repo cannot
drift into claiming eval coverage it does not have.
"""

import json
import re
from pathlib import Path
from typing import Any

REPORT = Path(__file__).parent.parent / "evals" / "results" / "latest.json"

SCENARIO_NAMES = {
    "approve-capacity-2",
    "defer-capacity-2",
    "approve-capacity-1",
    "approve-capacity-5",
    "chaos-notes-timeout-approve-2",
}
DETERMINISTIC_EVALUATORS = {
    "run-shape",
    "ranked-queue-called",
    "commit-called",
    "chaos-degradation",
}


def load_report() -> dict[str, Any]:
    assert REPORT.exists(), (
        "evals/results/latest.json is missing; run `uv run python -m evals.run_evals` "
        "with AWS credentials and commit the report"
    )
    report: dict[str, Any] = json.loads(REPORT.read_text())
    return report


def test_report_is_well_formed() -> None:
    report = load_report()
    assert re.fullmatch(r"[0-9a-f]{40}", report["git_sha"]), "report must record a full git SHA"
    assert report["total"] == len(report["verdicts"]) > 0
    assert report["passed"] == sum(1 for v in report["verdicts"] if v["passed"])
    assert report["seed"] == "synthetic_intake.json"


def test_report_covers_the_code_actually_in_this_tree() -> None:
    """A stale report is a false green: the recorded run must have covered
    the agent layer, engine, harness, and seed exactly as they exist in
    this tree. Any covered change requires regenerating the live evals
    (`uv run python -m evals.run_evals` with AWS credentials) and
    committing the new report alongside the change."""
    from evals.run_evals import compute_inputs_digest

    report = load_report()
    assert report["inputs_digest"] == compute_inputs_digest(), (
        "evals/results/latest.json was generated against different code, "
        "seed, or harness contents than this tree; re-run the live evals "
        "and commit the regenerated report with your change"
    )


def test_every_scenario_present() -> None:
    report = load_report()
    assert {v["case"] for v in report["verdicts"]} == SCENARIO_NAMES


def test_deterministic_evaluators_all_passed() -> None:
    report = load_report()
    rows = [v for v in report["verdicts"] if v["evaluator"] in DETERMINISTIC_EVALUATORS]
    assert rows, "no deterministic evaluator rows recorded"
    failures = [f"{v['case']}::{v['evaluator']}: {v['reason']}" for v in rows if not v["passed"]]
    assert not failures, "deterministic eval failures recorded: " + "; ".join(failures)


def test_llm_judges_recorded_and_passing() -> None:
    report = load_report()
    assert report["llm_judges_included"], (
        "the committed report must be the full run (LLM judges included); "
        "--skip-llm output is not the judged artifact"
    )
    rows = [v for v in report["verdicts"] if v["evaluator"] not in DETERMINISTIC_EVALUATORS]
    assert rows, "no LLM judge rows recorded"
    pass_rate = sum(1 for v in rows if v["passed"]) / len(rows)
    assert pass_rate >= 0.75, f"LLM judge pass rate {pass_rate:.2f} below 0.75"
